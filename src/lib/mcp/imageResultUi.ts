import "server-only";

export const MARO_IMAGE_RESULT_RESOURCE_URI = "ui://maro/image-result-v1.html";
export const MCP_APP_HTML_MIME_TYPE = "text/html;profile=mcp-app";

const FALLBACK_STORAGE_ORIGIN = "https://pbhzobqpavkuttdipjaq.supabase.co";

function storageOrigin(): string {
  const configured = process.env.NEXT_PUBLIC_SUPABASE_URL?.trim();
  if (!configured) return FALLBACK_STORAGE_ORIGIN;

  try {
    const url = new URL(configured);
    return url.protocol === "https:" ? url.origin : FALLBACK_STORAGE_ORIGIN;
  } catch {
    return FALLBACK_STORAGE_ORIGIN;
  }
}

export function getMaroImageResultResourceMeta() {
  const resourceDomains = [storageOrigin()];
  return {
    ui: {
      prefersBorder: true,
      csp: {
        connectDomains: [],
        resourceDomains,
      },
    },
    "openai/widgetDescription":
      "Displays the single image created by Maro for the connected user's active workspace.",
    "openai/widgetPrefersBorder": true,
    "openai/widgetCSP": {
      connect_domains: [],
      resource_domains: resourceDomains,
    },
  };
}

